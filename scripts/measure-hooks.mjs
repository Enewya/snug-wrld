// Measures the hook loop and garment bounds of every garment photo and writes them into lib/products.ts.
//
//   node scripts/measure-hooks.mjs      (run after scripts/cutout.mjs)
//
// For each served photo (public/products/*.webp), in image pixels:
//   hookApexX/Y      crest of the hook (top-most opaque row, centre of its pixels)
//   loopTopY         outer top of the loop (= hookApexY)
//   loopCenterX      horizontal centre of the curl (tip ball to the far side of the arc)
//   loopInnerTopY    first empty row inside the curl, under the arc, at loopCenterX
//   loopInnerBottomY bottom of the gap: the S-bend crossing back at loopCenterX, or just below the
//                    ball tip if that comes first (a rod through the curl must hide the tip)
//   neckY            top of the walnut neck (where the hook enters the wood)
//   garmentTopY/garmentBottomY  alpha bounds of hook + hanger + garment
//   shoulderY/X0/X1  the widest row in the garment's top third (shoulders / sleeve tips)
//   garmentX0/X1     horizontal alpha bounds of the garment below the hanger neck
// The rack runs the rod through the loop's inner gap and scales photos by garment height.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";
import { measure } from "../lib/measureHook.mjs";

const START = "// <generated by scripts/measure-hooks.mjs>";
const END = "// </generated>";

const files = readdirSync("public/products")
  .filter((f) => /-(side|front|back)\.webp$/.test(f))
  .map((f) => `/products/${f}`)
  .sort();

const rows = [];
const gaps = [];
for (const src of files) {
  const { data, info } = await sharp(join("public", src)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const m = measure(data, info.width, info.height);
  gaps.push(m.innerBottom - m.innerTop);
  rows.push(
    `  "${src}": { width: ${info.width}, height: ${info.height}, hookApexX: ${m.apexX}, hookApexY: ${m.apexY}, ` +
      `loopTopY: ${m.apexY}, loopCenterX: ${m.cx}, loopInnerTopY: ${m.innerTop}, loopInnerBottomY: ${m.innerBottom}, ` +
      `neckY: ${m.neckY}, garmentTopY: ${m.apexY}, garmentBottomY: ${m.bottom}, ` +
      `shoulderY: ${m.shoulder.y}, shoulderX0: ${m.shoulder.x0}, shoulderX1: ${m.shoulder.x1}, ` +
      `garmentX0: ${m.left}, garmentX1: ${m.right} },`,
  );
  console.log(
    src.padEnd(46),
    `apex ${m.apexX},${m.apexY}`.padEnd(13),
    `loop cx ${m.cx} inner ${m.innerTop}..${m.innerBottom} (gap ${m.innerBottom - m.innerTop})`.padEnd(36),
    `neck ${m.neckY}  garment ${m.apexY}..${m.bottom} (h ${m.bottom - m.apexY})  shoulders ${m.shoulder.x0}..${m.shoulder.x1} @${m.shoulder.y}`,
    m.apexY === 0 ? " <- hook touches the top edge (cropped)" : "",
  );
}
gaps.sort((a, b) => a - b);
console.log(`inner gap (image px): min ${gaps[0]}  median ${gaps[gaps.length >> 1]}  max ${gaps[gaps.length - 1]}`);

const block = `${START}
/** Hook loop + garment bounds of each photo, in image pixels. Regenerate with: node scripts/measure-hooks.mjs */
export const photos: Record<string, Photo> = {
${rows.join("\n")}
};
${END}`;

const path = "lib/products.ts";
const ts = readFileSync(path, "utf8");
const a = ts.indexOf(START), b = ts.indexOf(END);
if (a < 0 || b < 0) throw new Error(`markers not found in ${path}`);
writeFileSync(path, ts.slice(0, a) + block + ts.slice(b + END.length));
console.log(`updated ${path} (${rows.length} photos)`);
