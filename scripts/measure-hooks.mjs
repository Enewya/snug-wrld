// Measures the hook loop and garment bounds of every garment photo and writes them into lib/products.ts.
//
//   node scripts/measure-hooks.mjs      (run after scripts/cutout.mjs)
//
// For each served photo (public/products/*.webp), in image pixels:
//   hookApexX/Y      crest of the hook (top-most opaque row, centre of its pixels)
//   loopTopY         outer top of the loop (= hookApexY)
//   loopCenterX      horizontal centre of the curl (tip ball to the far side of the arc)
//   loopInnerTopY    first empty row inside the curl, under the arc, at loopCenterX
//   loopInnerBottomY bottom of the gap: the S-bend crossing back at loopCenterX, or just below the
//                    ball tip if that comes first (a rod through the curl must hide the tip)
//   neckY            top of the walnut neck (where the hook enters the wood)
//   garmentTopY/garmentBottomY  alpha bounds of hook + hanger + garment
//   shoulderY/X0/X1  the widest row in the garment's top third (shoulders / sleeve tips)
//   garmentX0/X1     horizontal alpha bounds of the garment below the hanger neck
// The rack runs the rod through the loop's inner gap and scales photos by garment height.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const OPAQUE = 128;
/** The wire's bright highlight is partly keyed out by the cutout; bridge holes this small. */
const BRIDGE = 3;
const START = "// <generated by scripts/measure-hooks.mjs>";
const END = "// </generated>";

const files = readdirSync("public/products")
  .filter((f) => /-(side|front|back)\.webp$/.test(f))
  .map((f) => `/products/${f}`)
  .sort();

function measure(data, W, H) {
  const op = (x, y) => x >= 0 && y >= 0 && x < W && y < H && data[(y * W + x) * 4 + 3] > OPAQUE;
  const rowXs = (y, x0 = 0, x1 = W - 1) => { const xs = []; for (let x = x0; x <= x1; x++) if (op(x, y)) xs.push(x); return xs; };

  let apexY = 0;
  while (apexY < H && rowXs(apexY).length === 0) apexY++;
  const top = rowXs(apexY);
  const apexX = Math.round((top[0] + top[top.length - 1]) / 2);

  // neck: first row of 12 in a row whose widest solid run near the hook is wider than the wire
  const solidRun = (y) => {
    let best = 0, start = -1;
    for (let x = apexX - 120; x <= apexX + 120; x++) {
      if (op(x, y)) { if (start < 0) start = x; best = Math.max(best, x - start + 1); } else start = -1;
    }
    return best;
  };
  let neckY = apexY;
  while (neckY < apexY + 500 && ![...Array(12).keys()].every((k) => solidRun(neckY + k) > 24)) neckY++;

  // curl extent: upper 60% of the hook
  let minX = W, maxX = 0;
  for (let y = apexY; y < apexY + (neckY - apexY) * 0.6; y++) {
    const xs = rowXs(y, apexX - 150, apexX + 150);
    if (xs.length) { minX = Math.min(minX, xs[0]); maxX = Math.max(maxX, xs[xs.length - 1]); }
  }
  const cx = Math.round((minX + maxX) / 2);

  // scan down a 3px column at cx: arc wire, then the gap, then the S-bend
  const col = (y) => op(cx - 1, y) || op(cx, y) || op(cx + 1, y);
  const colBridged = (y) => [...Array(BRIDGE + 1).keys()].some((k) => col(y + k)) && col(y - 1) ? true : col(y);
  let y = apexY;
  while (y < neckY && !col(y)) y++; // the crest may sit off the centre column
  while (y < neckY && colBridged(y)) y++;
  const innerTop = y;
  while (y < neckY && !col(y)) y++;
  const sBend = y;
  // bottom of the ball tip: the tip hangs on one side of the curl (left or right, depending on the
  // photo); on the other side the wire runs on down into the stem. Take the side that ends first.
  const sideBottom = (x0, x1) => {
    let b = innerTop;
    for (let yy = innerTop; yy < sBend; yy++) if (rowXs(yy, Math.round(x0), Math.round(x1)).length) b = yy;
    return b;
  };
  const q = (maxX - minX) * 0.25;
  const tipBottom = Math.min(sideBottom(minX, minX + q), sideBottom(maxX - q, maxX));
  // the inner gap ends at whichever comes first: the S-bend crossing back, or just below the tip
  const innerBottom = Math.min(sBend, tipBottom + 2);

  let bottom = 0;
  for (let yy = H - 1; yy >= 0 && !bottom; yy--) if (rowXs(yy).length) bottom = yy;
  // horizontal alpha bounds of the whole garment (below the hanger neck)
  let left = W, right = 0;
  for (let yy = neckY; yy <= bottom; yy += 2) {
    const xs = rowXs(yy);
    if (xs.length) { left = Math.min(left, xs[0]); right = Math.max(right, xs[xs.length - 1]); }
  }

  // shoulder line: the widest row in the top third of the garment (below the hanger neck)
  let shoulder = { y: neckY, x0: 0, x1: 0 };
  for (let yy = neckY; yy < neckY + (bottom - neckY) * 0.35; yy += 2) {
    const xs = rowXs(yy);
    if (xs.length && xs[xs.length - 1] - xs[0] > shoulder.x1 - shoulder.x0) shoulder = { y: yy, x0: xs[0], x1: xs[xs.length - 1] };
  }
  return { apexX, apexY, cx, innerTop, innerBottom, neckY, bottom, shoulder, left, right };
}

const rows = [];
const gaps = [];
for (const src of files) {
  const { data, info } = await sharp(join("public", src)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const m = measure(data, info.width, info.height);
  gaps.push(m.innerBottom - m.innerTop);
  rows.push(
    `  "${src}": { width: ${info.width}, height: ${info.height}, hookApexX: ${m.apexX}, hookApexY: ${m.apexY}, ` +
      `loopTopY: ${m.apexY}, loopCenterX: ${m.cx}, loopInnerTopY: ${m.innerTop}, loopInnerBottomY: ${m.innerBottom}, ` +
      `neckY: ${m.neckY}, garmentTopY: ${m.apexY}, garmentBottomY: ${m.bottom}, ` +
      `shoulderY: ${m.shoulder.y}, shoulderX0: ${m.shoulder.x0}, shoulderX1: ${m.shoulder.x1}, ` +
      `garmentX0: ${m.left}, garmentX1: ${m.right} },`,
  );
  console.log(
    src.padEnd(46),
    `apex ${m.apexX},${m.apexY}`.padEnd(13),
    `loop cx ${m.cx} inner ${m.innerTop}..${m.innerBottom} (gap ${m.innerBottom - m.innerTop})`.padEnd(36),
    `neck ${m.neckY}  garment ${m.apexY}..${m.bottom} (h ${m.bottom - m.apexY})  shoulders ${m.shoulder.x0}..${m.shoulder.x1} @${m.shoulder.y}`,
    m.apexY === 0 ? " <- hook touches the top edge (cropped)" : "",
  );
}
gaps.sort((a, b) => a - b);
console.log(`inner gap (image px): min ${gaps[0]}  median ${gaps[gaps.length >> 1]}  max ${gaps[gaps.length - 1]}`);

const block = `${START}
/** Hook loop + garment bounds of each photo, in image pixels. Regenerate with: node scripts/measure-hooks.mjs */
export const photos: Record<string, Photo> = {
${rows.join("\n")}
};
${END}`;

const path = "lib/products.ts";
const ts = readFileSync(path, "utf8");
const a = ts.indexOf(START), b = ts.indexOf(END);
if (a < 0 || b < 0) throw new Error(`markers not found in ${path}`);
writeFileSync(path, ts.slice(0, a) + block + ts.slice(b + END.length));
console.log(`updated ${path} (${rows.length} photos)`);
