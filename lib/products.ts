/**
 * Display scale of each photo relative to its product's side photo, so a garment is the same real
 * size whichever photo shows: side = 1, front/back = side garment height ÷ their garment height.
 */
export const photoScale: Record<string, number> = {};
const garmentH = (src: string) => photos[src].garmentBottomY - photos[src].garmentTopY;

/** Side/front/back paths for a photo base name; back only if that file exists. */
function views(base: string) {
  const back = `/products/${base}-back.png`;
  const v = {
    side: `/products/cut/${base}-side.png`,
    front: `/products/cut/${base}-front.png`,
    back: back in photos ? back : undefined,
  };
  for (const src of [v.side, v.front, v.back]) if (src) photoScale[src] = garmentH(v.side) / garmentH(src);
  return v;
}

/** Each product's own page in the shop (SEE AVAILABILITY in the focus view). */
const SHOP = "https://checkout.snugwrld.com/products/";

const single = (slug: string, name: string, colour: string, url: string): Product => ({ slug, name, colour, ...views(slug), url });

function withColourways(slug: string, name: string, url: string, ways: [label: string, hex: string, base: string][]): Product {
  const colourways = ways.map(([label, hex, base]) => ({ label, hex, ...views(base) }));
  fitColourways(colourways);
  const { side, front, back } = colourways[0];
  return { slug, name, side, front, back, colourways, url };
}

/**
 * Colourway photos of one product are shot slightly differently. In the focus view every colourway
 * photo is fitted onto the product's first colourway (same view): its hook's vertical position, its
 * shoulder width and its hem line are matched exactly (separate x / y scale) and its shoulders are
 * centred on the reference's. A colour switch then changes only the colour, never the outline.
 */
export type ColourFit = { ref: string; sx: number; sy: number };
export const colourFit: Record<string, ColourFit> = {};
const hookY = (m: Photo) => (m.loopInnerTopY + m.loopInnerBottomY) / 2;
function fitColourways(ways: Colourway[]) {
  for (const view of ["front", "back"] as const) {
    const ref = ways[0][view];
    if (!ref) continue;
    const r = photos[ref];
    for (const w of ways.slice(1)) {
      const src = w[view];
      if (!src) continue;
      const m = photos[src];
      colourFit[src] = {
        ref,
        sx: (r.shoulderX1 - r.shoulderX0) / (m.shoulderX1 - m.shoulderX0),
        sy: (r.garmentBottomY - hookY(r)) / (m.garmentBottomY - hookY(m)),
      };
    }
  }
}

/** "Name — Colour", as in the rack's hover caption. */
export const captionOf = (p: Product) => {
  const colour = p.colourways?.[0].label ?? p.colour;
  return colour ? `${p.name} — ${colour}` : p.name;
};

