/**
 * Photos (public/products/<base>-{side,front,back}.png) include the hanger.
 * side/front are cut out by `node scripts/cutout.mjs` into public/products/cut/; back already has alpha.
 * `node scripts/measure-hooks.mjs` then records each photo's hook loop and garment bounds in `photos` below.
 */
export type Colourway = { label: string; hex: string; side: string; front: string; back?: string };

export type Product = {
  slug: string;
  name: string;
  /** Colour name for the rack caption (products with colourways use the first colourway's label). */
  colour?: string;
  side: string;
  front: string;
  back?: string;
  /** First colourway is the one hanging on the rack. */
  colourways?: Colourway[];
  url: string;
};

/** Measured in image pixels by scripts/measure-hooks.mjs. */
export type Photo = {
  width: number;
  height: number;
  hookApexX: number;
  hookApexY: number;
  /** Outer top of the hook loop. */
  loopTopY: number;
  loopCenterX: number;
  /** The loop's inner gap (under the arc, down to the ball tip): the rod passes through here. */
  loopInnerTopY: number;
  loopInnerBottomY: number;
  /** Top of the walnut neck: everything above is hook. */
  neckY: number;
  garmentTopY: number;
  garmentBottomY: number;
  /** Widest row in the garment's top third (shoulders / sleeve tips). */
  shoulderY: number;
  shoulderX0: number;
  shoulderX1: number;
  /** Horizontal alpha bounds of the garment below the hanger neck. */
  garmentX0: number;
  garmentX1: number;
};

